package com.soulreturns.features.profileviewer.gui

import com.soulreturns.features.profileviewer.gui.kit.Ui

/**
 * One rail entry of the Profile Viewer and the body it shows. One object per file under
 * `gui/sections/`, listed once in [ProfileSections.ALL]; nothing else in the shell knows a section.
 *
 * [build] is pure: it reads [ProfileContext] and appends nodes to [Ui]. It runs every frame, so
 * expensive work (decoding item blobs, sorting thousands of rows) belongs in a cache keyed by the
 * member (see [ProfileItems]) and side effects only in click lambdas.
 */
interface ProfileSection {
    /** Stable id: keyboard shortcuts, cross-section links (`ctx.open("skills")`) and the view state use it. */
    val id: String

    /** Rail label and section header title. */
    val title: String

    /** One of the `GROUP_*` constants; the rail draws a label where the group changes. */
    val group: String

    /** Line icon (`pv_*`, generated by `scripts/config_icons.mjs` from the mock). */
    val icon: String

    /** The dim line beside the section header title, or null. */
    val subtitle: String? get() = null

    /** Whether this section has a rail entry for this player at all (default: always). */
    fun visible(ctx: ProfileContext): Boolean = true

    /**
     * Null when everything this section needs arrived. Otherwise the reason it is (partly) hidden,
     * shown as a lock in the rail with this text as its tooltip ("API toggle off").
     */
    fun locked(ctx: ProfileContext): String? = null

    /** The faint number at the rail entry's right ("53.6", "T10"), or null. */
    fun badge(ctx: ProfileContext): String? = null

    /** Rail entry in a muted color (the Soul entry when there is no Soul data). */
    fun muted(ctx: ProfileContext): Boolean = false

    fun build(ctx: ProfileContext, ui: Ui)

    companion object {
        const val GROUP_TOP = ""
        const val GROUP_ITEMS = "Items"
        const val GROUP_PROGRESS = "Progress"
        const val GROUP_ACTIVITIES = "Activities"
        const val GROUP_OTHER = "Other"

        /** Pinned at the bottom of the rail, after a separator. */
        const val GROUP_SOUL = "soul"
    }
}
